param(
    [string]$Cabal = 'cabal',
    [string]$Ghc = 'ghc',
    [string]$ProjectFile = 'cabal.project',
    [string]$BuildDirectory = 'dist-newstyle',
    [switch]$Offline,
    [switch]$SkipTests
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not [IO.Path]::IsPathRooted($ProjectFile)) { $ProjectFile = Join-Path $root $ProjectFile }
if (-not [IO.Path]::IsPathRooted($BuildDirectory)) { $BuildDirectory = Join-Path $root $BuildDirectory }
$ProjectFile = (Resolve-Path -LiteralPath $ProjectFile).Path
$BuildDirectory = [IO.Path]::GetFullPath($BuildDirectory)
$checkoutPrefix = $root + [IO.Path]::DirectorySeparatorChar
if (-not $ProjectFile.StartsWith($checkoutPrefix, [StringComparison]::OrdinalIgnoreCase) -or
    -not $BuildDirectory.StartsWith($checkoutPrefix, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Choose a project file and build directory inside the Stillroom checkout.'
}
$projectArgs = @("--project-file=$ProjectFile", "--builddir=$BuildDirectory", "--with-compiler=$Ghc")
$cabalPaths = & $Cabal path --ignore-project --output-format=json "--with-compiler=$Ghc" | ConvertFrom-Json
if ($LASTEXITCODE) { throw 'Package cache lookup failed.' }
$prepareArgs = @('--cache', (Join-Path $cabalPaths.'remote-repo-cache' 'hackage.haskell.org'))
if ($Offline) { $prepareArgs += '--offline' }
& python (Join-Path $PSScriptRoot 'prepare-native-dependencies.py') @prepareArgs
if ($LASTEXITCODE) { throw 'Pinned Haskell dependency preparation failed.' }

$vendor = Join-Path $root 'vendor/gmp'
New-Item -ItemType Directory -Force -Path $vendor | Out-Null

function Get-VerifiedFile([string]$Uri, [string]$Hash, [string]$File) {
    if (-not (Test-Path -LiteralPath $File)) {
        if ($Offline) { throw "Missing cached dependency: $File" }
        Invoke-WebRequest -Uri $Uri -OutFile $File
    }
    if ((Get-FileHash -LiteralPath $File -Algorithm SHA256).Hash.ToLowerInvariant() -ne $Hash) {
        throw "Dependency checksum mismatch: $File"
    }
}

# Use a replaceable native DLL instead of GHC's bundled static GMP objects.
# Pin both the binary package and its complete corresponding source recipe.
Get-VerifiedFile 'https://repo.msys2.org/mingw/ucrt64/mingw-w64-ucrt-x86_64-gmp-6.3.0-2-any.pkg.tar.zst' `
    'e82a75968a556484a50084578238a84eb60fb93e34986fd6695c537975bd39ea' (Join-Path $vendor 'gmp.pkg.tar.zst')
Get-VerifiedFile 'https://repo.msys2.org/mingw/sources/mingw-w64-gmp-6.3.0-2.src.tar.zst' `
    'f288f944fd9609db220bcf6a8dd0703a5674eeb906ef35eb8485bb8192135994' (Join-Path $vendor 'gmp.src.tar.zst')
foreach ($archive in @('gmp.pkg.tar.zst','gmp.src.tar.zst')) {
    tar -xf (Join-Path $vendor $archive) -C $vendor
    if ($LASTEXITCODE) { throw 'GMP extraction failed. A tar build with zstd support is required.' }
}
$importLibrary = (Join-Path $vendor 'ucrt64/lib/libgmp.dll.a').Replace('\','/')
$ghcLib = (& $Ghc --print-libdir).Trim()
$windres = Join-Path (Split-Path -Parent $ghcLib) 'mingw/bin/windres.exe'
$iconObject = Join-Path $root 'vendor/stillroom-icon.o'
Push-Location (Join-Path $root 'cbits')
try {
    & $windres -i icon.rc -o $iconObject -O coff
    if ($LASTEXITCODE) { throw 'Icon resource compilation failed.' }
} finally { Pop-Location }
$iconLink = $iconObject.Replace('\','/')
$local = "$ProjectFile.local"
$marker = '-- Generated by Stillroom build.ps1'
if ((Test-Path -LiteralPath $local) -and -not ([IO.File]::ReadAllText($local).StartsWith($marker))) {
    throw 'Preserve or rename your custom cabal.project.local before running this script.'
}
# Cabal can reuse an executable after linker-only option changes. Invalidate
# the local build when this configuration changes; leave cached dependencies.
# Our resource embeds the same asInvoker privilege boundary. GHC's automatic
# manifest puts the absolute output path in llvm-rc input, which fails on Unicode.
$gmpLink = "-optl-Wl,--whole-archive `"-optl$importLibrary`" -optl-Wl,--no-whole-archive"
$configuration = "$marker`npackage stillroom`n  ghc-options: -fno-embed-manifest $gmpLink `"-optl$iconLink`"`npackage haskell-game-io`n  ghc-options: $gmpLink`n"
$linkChanged = -not (Test-Path -LiteralPath $local) -or ([IO.File]::ReadAllText($local) -ne $configuration)
$beforePath = $env:PATH
$env:PATH = (Join-Path $vendor 'ucrt64/bin') + [IO.Path]::PathSeparator + $env:PATH
Push-Location $root
try {
    if ($linkChanged) {
        if (Test-Path -LiteralPath (Join-Path $BuildDirectory 'cache/plan.json')) {
            $build = Get-Item -LiteralPath $BuildDirectory
            if (-not $build.FullName.StartsWith($checkoutPrefix, [StringComparison]::OrdinalIgnoreCase)) {
                throw 'Choose a Cabal build directory inside this checkout.'
            }
            for ($directory = $build; $directory.FullName -ne $root; $directory = $directory.Parent) {
                if ($directory.Attributes -band [IO.FileAttributes]::ReparsePoint) {
                    throw 'Use a Cabal build directory with no reparse points below the checkout.'
                }
            }
            # Keep Cabal's fetched source-repository packages for offline rebuilds.
            foreach ($child in @('build', 'cache', 'packagedb')) {
                $path = Join-Path $build.FullName $child
                if (Test-Path -LiteralPath $path) {
                    $target = Get-Item -LiteralPath $path
                    if (-not $target.FullName.StartsWith($build.FullName + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or
                        ($target.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
                        throw "Unexpected build path: $path"
                    }
                    Remove-Item -LiteralPath $target.FullName -Recurse -Force
                }
            }
        }
        [IO.File]::WriteAllText($local, $configuration)
    }
    $offlineFlag = @()
    if ($Offline) { $offlineFlag = @('--offline') } else {
        & $Cabal update
        if ($LASTEXITCODE) { throw 'Package index update failed.' }
    }
    & $Cabal build exe:stillroom exe:gameio-audio-worker @projectArgs @offlineFlag
    if ($LASTEXITCODE) { throw 'Build failed.' }
    if (-not $SkipTests) {
        & $Cabal test laws --test-show-details=direct @projectArgs @offlineFlag
        if ($LASTEXITCODE) { throw 'Property tests failed.' }
        & (Join-Path $PSScriptRoot 'check-graphics-types.ps1') -Ghc $Ghc
    }
    & $Cabal check
    if ($LASTEXITCODE) { throw 'Package metadata check failed.' }
    # Cabal's console encoding may be a legacy code page on Windows. The UTF-8
    # build plan preserves Unicode paths when PowerShell captures native output.
    $plan = Get-Content -LiteralPath (Join-Path $BuildDirectory 'cache/plan.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    $executable = ($plan.'install-plan' | Where-Object { $_.'component-name' -eq 'exe:stillroom' }).'bin-file'
    $worker = ($plan.'install-plan' | Where-Object { $_.'component-name' -eq 'exe:gameio-audio-worker' }).'bin-file'
    $objdump = Join-Path (Split-Path -Parent $ghcLib) 'mingw/bin/objdump.exe'
    foreach ($binary in @($executable, $worker)) {
        if (-not $binary -or -not (Test-Path -LiteralPath $binary -PathType Leaf)) { throw 'Executable lookup failed.' }
        $imports = & $objdump -p $binary
        if ($LASTEXITCODE -or -not ($imports | Select-String 'DLL Name:\s+libgmp-10\.dll')) {
            throw "Executable does not use the replaceable GMP DLL: $binary"
        }
    }
    $binaryRoot = Split-Path -Parent $executable
    Copy-Item -LiteralPath $worker,(Join-Path $vendor 'ucrt64/bin/libgmp-10.dll') -Destination $binaryRoot
    Write-Output $executable
} finally {
    Pop-Location
    $env:PATH = $beforePath
}
